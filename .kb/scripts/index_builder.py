#!/usr/bin/env python3
from __future__ import annotations
"""
Knowledge Base Index Builder & Health Validator (index_builder.py)

Deterministic index builder for LLM-RE-WIKI:
1. Parses YAML frontmatter of all wiki articles in knowledge_base/wiki/
2. Deterministically generates secondary cross-topic index files:
   - knowledge_base/wiki/_tools-index.md
   - knowledge_base/wiki/_snippets-index.md
   - knowledge_base/wiki/_patterns-index.md
   - knowledge_base/wiki/_ttp-index.md
3. Validates link integrity (checks for dead [[...]] links and orphan articles)
4. Synchronizes graph_data.js for the visualizer
"""

import os
import re
import sys
import json
import argparse
from pathlib import Path
from datetime import datetime

# Optional PyYAML with fallback
try:
    import yaml
    HAS_YAML = True
except ImportError:
    HAS_YAML = False


def extract_frontmatter(text: str) -> tuple[dict, str]:
    """Extracts frontmatter and body from markdown content."""
    if not text.startswith("---"):
        return {}, text
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}, text
    fm_str = parts[1].strip()
    body = parts[2]
    if HAS_YAML:
        try:
            fm = yaml.safe_load(fm_str)
            if isinstance(fm, dict):
                return fm, body
        except Exception:
            pass
    # Fallback parser for key-value pairs
    data = {}
    for line in fm_str.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, val = line.split(":", 1)
        key = key.strip()
        val = val.strip()
        if val.startswith("[") and val.endswith("]"):
            items = [item.strip().strip("'\"") for item in val[1:-1].split(",") if item.strip()]
            data[key] = items
        else:
            data[key] = val.strip("'\"")
    return data, body


def get_wiki_files(wiki_dir: Path) -> list[Path]:
    """Returns all non-index markdown files."""
    files = []
    for p in wiki_dir.rglob("*.md"):
        # Ignore master index and secondary cross-topic indexes from content pool
        if p.name in ("_master-index.md", "_tools-index.md", "_snippets-index.md", "_patterns-index.md", "_ttp-index.md", "log.md"):
            continue
        files.append(p)
    return sorted(files)


def extract_links(content: str, source_path: Path, wiki_dir: Path) -> list[str]:
    """Extracts all wiki link targets from markdown content, resolving relative paths."""
    targets = []
    # Match [[wiki/path/file#anchor|alias]] or [[relative_file#anchor]]
    matches = re.findall(r"\[\[([^\]\|#]+)(?:#[^\]\|]+)?(?:\|[^\]]+)?\]\]", content)
    for raw in matches:
        target = raw.strip()
        if not target.startswith("wiki/"):
            # Relative to file parent
            rel_dir = source_path.parent.relative_to(wiki_dir)
            if str(rel_dir) != ".":
                target = f"wiki/{rel_dir}/{target}"
            else:
                target = f"wiki/{target}"
        if target.endswith(".md"):
            target = target[:-3]
        targets.append(target.lower())
    return targets


def build_tools_index(articles: list[dict], out_path: Path):
    """Builds knowledge_base/wiki/_tools-index.md"""
    tool_map = {}
    for a in articles:
        tools = a["fm"].get("tool_versions", [])
        if isinstance(tools, str):
            tools = [tools]
        for t in tools:
            # Match "Tool Version", e.g., "Frida 16.x" or "IDA 8.3"
            parts = str(t).strip().split(maxsplit=1)
            tool_name = parts[0]
            version = parts[1] if len(parts) > 1 else "unspecified"
            key = (tool_name, version)
            if key not in tool_map:
                tool_map[key] = []
            tool_map[key].append(a)

    lines = [
        "# Cross-Topic Index: Tools & Environment Versions",
        "",
        "> Auto-generated by `.kb/scripts/index_builder.py`. Do not edit manually.",
        f"> Last updated: {datetime.now().strftime('%Y-%m-%d')}",
        "",
        "| Tool | Tested Version | Referenced In | Primary Mechanism / Notes |",
        "|---|---|---|---|"
    ]

    for (tool_name, version), arts in sorted(tool_map.items()):
        links = ", ".join([f"[[{art['wiki_link']}|{art['title']}]]" for art in arts])
        notes = arts[0]["fm"].get("llm_summary", "")[:90] + "..." if arts[0]["fm"].get("llm_summary") else "-"
        notes = notes.replace("|", "\\|")
        lines.append(f"| {tool_name} | {version} | {links} | {notes} |")

    if len(tool_map) == 0:
        lines.append("| - | - | *(No tool versions indexed yet)* | - |")

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_snippets_index(articles: list[dict], out_path: Path):
    """Builds knowledge_base/wiki/_snippets-index.md"""
    snippet_articles = []
    for a in articles:
        tags = a["fm"].get("tags", [])
        if isinstance(tags, str):
            tags = [tags]
        type_str = str(a["fm"].get("type", ""))
        # Identify articles containing actionable bypasses/snippets
        if any(kw in " ".join(tags).lower() for kw in ("bypass", "hook", "script", "snippet", "frida", "payload", "ida")) or type_str in ("api-doc", "pentest-finding"):
            snippet_articles.append(a)

    lines = [
        "# Cross-Topic Index: Snippets & Bypass Scripts",
        "",
        "> Auto-generated by `.kb/scripts/index_builder.py`. Do not edit manually.",
        f"> Last updated: {datetime.now().strftime('%Y-%m-%d')}",
        "",
        "| Purpose / Technique | Type | Article | Tags | Summary |",
        "|---|---|---|---|---|"
    ]

    for a in sorted(snippet_articles, key=lambda x: x["title"]):
        tags = a["fm"].get("tags", [])
        tag_str = " ".join([f"#{t}" for t in tags[:4]])
        summary = a["fm"].get("llm_summary", "-")[:90].replace("|", "\\|")
        lines.append(f"| {a['title']} | {a['fm'].get('type', 'technique')} | [[{a['wiki_link']}|{a['title']}]] | {tag_str} | {summary} |")

    if not snippet_articles:
        lines.append("| - | - | *(No snippets indexed yet)* | - | - |")

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_patterns_index(articles: list[dict], out_path: Path):
    """Builds knowledge_base/wiki/_patterns-index.md"""
    lines = [
        "# Cross-Topic Index: Protection & Obfuscation Patterns",
        "",
        "> Auto-generated by `.kb/scripts/index_builder.py`. Do not edit manually.",
        f"> Last updated: {datetime.now().strftime('%Y-%m-%d')}",
        "",
        "| Pattern / Mechanism | Topic | Article | Complexity | Summary |",
        "|---|---|---|---|---|"
    ]

    for a in sorted(articles, key=lambda x: x["title"]):
        topic = a["topic"]
        complexity = a["fm"].get("complexity", "intermediate")
        summary = a["fm"].get("llm_summary", "-")[:90].replace("|", "\\|")
        lines.append(f"| {a['title']} | {topic} | [[{a['wiki_link']}|{a['title']}]] | {complexity} | {summary} |")

    if not articles:
        lines.append("| - | - | *(No patterns indexed yet)* | - | - |")

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_ttp_index(articles: list[dict], out_path: Path):
    """Builds knowledge_base/wiki/_ttp-index.md"""
    ttp_map = {}
    for a in articles:
        ttps = a["fm"].get("attack_ttps", a["fm"].get("attack_ttp", []))
        if isinstance(ttps, str):
            ttps = [ttps]
        for t in ttps:
            t_str = str(t).strip()
            if t_str not in ttp_map:
                ttp_map[t_str] = []
            ttp_map[t_str].append(a)

    lines = [
        "# Cross-Topic Index: ATT&CK TTPs & Defensive Evasion",
        "",
        "> Auto-generated by `.kb/scripts/index_builder.py`. Do not edit manually.",
        f"> Last updated: {datetime.now().strftime('%Y-%m-%d')}",
        "",
        "| TTP ID | Name / Description | Referenced In | Notes |",
        "|---|---|---|---|"
    ]

    for ttp, arts in sorted(ttp_map.items()):
        links = ", ".join([f"[[{art['wiki_link']}|{art['title']}]]" for art in arts])
        notes = arts[0]["fm"].get("llm_summary", "")[:80] + "..." if arts[0]["fm"].get("llm_summary") else "-"
        notes = notes.replace("|", "\\|")
        lines.append(f"| {ttp} | - | {links} | {notes} |")

    if not ttp_map:
        lines.append("| - | - | *(No ATT&CK TTPs indexed yet)* | - |")

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def validate_health(wiki_dir: Path, articles: list[dict]) -> tuple[list[str], list[str]]:
    """Checks for dead links and orphan articles."""
    known_nodes = set()
    for p in wiki_dir.rglob("*.md"):
        rel = p.relative_to(wiki_dir).as_posix()
        if rel.endswith(".md"):
            rel = rel[:-3]
        known_nodes.add(f"wiki/{rel}".lower())

    dead_links = []
    referenced_nodes = set()

    for a in articles:
        targets = extract_links(a["content"], a["path"], wiki_dir)
        for t in targets:
            referenced_nodes.add(t)
            if t not in known_nodes:
                dead_links.append(f"{a['rel_path']} -> [[{t}]]")

    orphans = []
    for a in articles:
        link_id = a["wiki_link"].lower()
        if link_id not in referenced_nodes and not a["path"].name.startswith("_"):
            orphans.append(a["rel_path"])

    return dead_links, orphans


def main():
    parser = argparse.ArgumentParser(description="Deterministic KB Index Builder and Validator")
    parser.add_argument("--check", action="store_true", help="Lint and validate only, do not write files")
    parser.add_argument("--graph", action="store_true", help="Also rebuild graph_data.js")
    parser.add_argument("--open", action="store_true", help="Open knowledge graph visualizer in browser")
    args = parser.parse_args()

    project_root = Path(__file__).resolve().parent.parent.parent
    wiki_dir = project_root / "knowledge_base" / "wiki"

    if not wiki_dir.exists():
        print(f"Error: Wiki directory not found at {wiki_dir}")
        sys.exit(1)

    files = get_wiki_files(wiki_dir)
    articles = []

    for f in files:
        text = f.read_text(encoding="utf-8")
        fm, body = extract_frontmatter(text)
        rel_posix = f.relative_to(wiki_dir).as_posix()
        link_name = f"wiki/{rel_posix[:-3]}" if rel_posix.endswith(".md") else f"wiki/{rel_posix}"
        
        # Derive title
        title = None
        for line in body.splitlines():
            line = line.strip()
            if line.startswith("# ") and not line.startswith("## "):
                title = line[2:].strip()
                break
        if not title:
            title = f.stem.replace("-", " ").title()

        topic = rel_posix.split("/")[0] if "/" in rel_posix else "general"

        articles.append({
            "path": f,
            "rel_path": str(f.relative_to(project_root)),
            "wiki_link": link_name,
            "title": title,
            "topic": topic,
            "fm": fm,
            "content": text
        })

    dead_links, orphans = validate_health(wiki_dir, articles)

    print(f"[*] Scanned {len(articles)} wiki articles.")
    if dead_links:
        print(f"[!] Warning: {len(dead_links)} dead links detected:")
        for dl in dead_links[:10]:
            print(f"    - {dl}")
    else:
        print("[✓] Zero dead links detected.")

    if orphans:
        print(f"[*] Note: {len(orphans)} orphan articles (not linked from other files yet):")
        for o in orphans[:5]:
            print(f"    - {o}")
    else:
        print("[✓] Zero orphan articles.")

    if args.check:
        print("[*] Check mode complete.")
        return

    if not articles:
        print("[*] No articles in wiki yet. Skipping index generation.")
        return

    # Generate secondary indexes
    print("[*] Generating cross-topic indexes...")
    build_tools_index(articles, wiki_dir / "_tools-index.md")
    build_snippets_index(articles, wiki_dir / "_snippets-index.md")
    build_patterns_index(articles, wiki_dir / "_patterns-index.md")
    build_ttp_index(articles, wiki_dir / "_ttp-index.md")
    print("[✓] Updated _tools-index.md, _snippets-index.md, _patterns-index.md, _ttp-index.md")

    # Sync graph
    graph_script = project_root / ".kb" / "scripts" / "graph_generator.py"
    if graph_script.exists():
        import subprocess
        cmd = [sys.executable, str(graph_script)]
        if args.open:
            cmd.append("--open")
        subprocess.run(cmd)


if __name__ == "__main__":
    main()
