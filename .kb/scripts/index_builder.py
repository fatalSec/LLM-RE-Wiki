#!/usr/bin/env python3
"""
Knowledge Base Index Builder & Health Validator (index_builder.py)

Deterministic index builder for LLM-RE-WIKI. The AI never edits these files.

1. Parses the YAML frontmatter of every article in knowledge_base/wiki/
2. Generates (only rewriting a file when its content actually changed):
   - knowledge_base/wiki/_master-index.md  one compact line per article (agent's search entry point)
   - knowledge_base/wiki/_tools-index.md   tool + version -> articles
   - knowledge_base/wiki/_ttp-index.md     MITRE ATT&CK TTP -> articles
3. Health check:
   - Errors (exit code 1): dead [[links]], missing/invalid frontmatter
   - Notes: orphan articles, articles with no outgoing links, raw files not compiled yet
4. Synchronizes graph_data.js for the visualizer

Usage:
    python3 .kb/scripts/index_builder.py            # rebuild indexes + graph, report health
    python3 .kb/scripts/index_builder.py --check    # report health only, write nothing
    python3 .kb/scripts/index_builder.py --open     # rebuild and open the graph
"""
from __future__ import annotations

import os
import re
import sys
import argparse
import tempfile
from pathlib import Path

# Optional PyYAML with fallback
try:
    import yaml
    HAS_YAML = True
except ImportError:
    HAS_YAML = False


MASTER_INDEX = "_master-index.md"
TOOLS_INDEX = "_tools-index.md"
TTP_INDEX = "_ttp-index.md"
# Older versions generated these; they are removed automatically (the master index replaces them).
LEGACY_INDEXES = ("_patterns-index.md", "_snippets-index.md")
GENERATED_MARKER = "Auto-generated by `.kb/scripts/index_builder.py`"
SKIP_FILES = {MASTER_INDEX, TOOLS_INDEX, TTP_INDEX, "log.md", *LEGACY_INDEXES}

# `sources` (list) is preferred; a single legacy `source` is still accepted.
REQUIRED_FIELDS = ("type", "topic", "tags", "complexity", "completeness", "last_verified", "llm_summary")
# Must match the `type:` values in .kb/schemas/*.md
VALID_TYPES = ("blog", "analysis-notes", "api-doc", "pentest-finding", "malware-analysis", "research-paper")
SUMMARY_MAX_CHARS = 120
MAX_TAGS = 6


# ---------------------------------------------------------------------------
# Parsing helpers
# ---------------------------------------------------------------------------

def extract_frontmatter(text: str) -> tuple[dict, str]:
    """Extracts frontmatter and body from markdown content."""
    if not text.startswith("---"):
        return {}, text
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}, text
    fm_str = parts[1].strip()
    body = parts[2]
    if HAS_YAML:
        try:
            fm = yaml.safe_load(fm_str)
            if isinstance(fm, dict):
                return fm, body
        except Exception:
            pass
    # Fallback parser for key-value pairs
    data = {}
    for line in fm_str.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, val = line.split(":", 1)
        key = key.strip()
        val = val.strip()
        if val.startswith("[") and val.endswith("]"):
            items = [item.strip().strip("'\"") for item in val[1:-1].split(",") if item.strip()]
            data[key] = items
        else:
            data[key] = val.strip("'\"")
    return data, body


def as_list(value) -> list[str]:
    """Normalizes a frontmatter value (list, string, or missing) into a list of strings."""
    if value is None or value == "":
        return []
    if isinstance(value, (list, tuple)):
        return [str(v).strip() for v in value if str(v).strip()]
    return [str(value).strip()]


def article_sources(fm: dict) -> list[str]:
    """Returns the article's sources from `sources:` (preferred) or legacy `source:`."""
    return as_list(fm.get("sources")) or as_list(fm.get("source"))


def split_tool_version(entry: str) -> tuple[str, str]:
    """Splits 'IDA Pro 8.3' into ('IDA Pro', '8.3'). The version is the last word,
    but only if it starts with a digit (or 'v' + digit); otherwise there is no version."""
    entry = str(entry).strip()
    parts = entry.rsplit(maxsplit=1)
    if len(parts) == 2 and re.match(r"^v?\d", parts[1], re.IGNORECASE):
        return parts[0], parts[1]
    return entry, "unspecified"


def shorten(text: str, limit: int = SUMMARY_MAX_CHARS) -> str:
    """Collapses whitespace and cuts at a word boundary."""
    text = " ".join(str(text).split()).replace("|", "/")
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(",;:.")
    return cut + "…"


def get_wiki_files(wiki_dir: Path) -> list[Path]:
    """Returns all wiki markdown files except generated indexes and the log."""
    return sorted(p for p in wiki_dir.rglob("*.md") if p.name not in SKIP_FILES)


def extract_links(content: str, source_path: Path, wiki_dir: Path) -> list[str]:
    """Extracts all wiki link targets from markdown content, resolving relative paths."""
    targets = []
    # Match [[wiki/path/file#anchor|alias]] or [[relative_file#anchor]]
    matches = re.findall(r"\[\[([^\]\|#]+)(?:#[^\]\|]+)?(?:\|[^\]]+)?\]\]", content)
    for raw in matches:
        target = raw.strip()
        if not target.startswith("wiki/"):
            # Relative to file parent
            rel_dir = source_path.parent.relative_to(wiki_dir)
            if str(rel_dir) != ".":
                target = f"wiki/{rel_dir}/{target}"
            else:
                target = f"wiki/{target}"
        if target.endswith(".md"):
            target = target[:-3]
        targets.append(target.lower())
    return targets


def is_article(a: dict) -> bool:
    """Real articles, as opposed to navigation pages such as _index.md or _hub.md."""
    return not a["path"].name.startswith("_")


# ---------------------------------------------------------------------------
# File writing
# ---------------------------------------------------------------------------

def write_if_changed(path: Path, content: str) -> bool:
    """Atomically writes `content` to `path` only if it differs. Returns True if written."""
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise
    return True


def header(title: str, note: str) -> list[str]:
    return [f"# {title}", "", f"> {GENERATED_MARKER} — do not edit manually. {note}", ""]


# ---------------------------------------------------------------------------
# Index builders (each returns the file content)
# ---------------------------------------------------------------------------

def build_master_index(articles: list[dict]) -> str:
    """One compact line per article, grouped by topic folder: link | tags | summary."""
    groups: dict[str, list[dict]] = {}
    for a in articles:
        if is_article(a):
            groups.setdefault(a["topic"], []).append(a)

    lines = header(
        "Master Index",
        "Format: `link | tags | summary`. Specific question → `rg` the wiki first. "
        "Broad question → scan this file (or `rg -i \"<term>\"` it), then open the matching articles.",
    )
    if not groups:
        lines.append("*(No articles yet.)*")
    for topic in sorted(groups):
        arts = sorted(groups[topic], key=lambda x: x["wiki_link"])
        lines += [f"## {topic} ({len(arts)})", ""]
        for a in arts:
            tags = ", ".join(as_list(a["fm"].get("tags"))[:MAX_TAGS]) or "-"
            summary = shorten(a["fm"].get("llm_summary") or a["title"])
            lines.append(f"- [[{a['wiki_link']}]] | {tags} | {summary}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def build_tools_index(articles: list[dict]) -> str:
    """Tool + tested version -> articles."""
    tool_map: dict[tuple[str, str], list[dict]] = {}
    for a in articles:
        for t in as_list(a["fm"].get("tool_versions")):
            tool_map.setdefault(split_tool_version(t), []).append(a)

    lines = header("Tools & Versions Index", "Which articles cover a given tool or version.")
    lines += ["| Tool | Version | Articles |", "|---|---|---|"]
    for (tool, version), arts in sorted(tool_map.items(), key=lambda kv: (kv[0][0].lower(), kv[0][1])):
        links = ", ".join(f"[[{art['wiki_link']}|{art['title']}]]" for art in arts)
        lines.append(f"| {tool} | {version} | {links} |")
    if not tool_map:
        lines.append("| - | - | *(No tool versions indexed yet)* |")
    return "\n".join(lines) + "\n"


def build_ttp_index(articles: list[dict]) -> str:
    """MITRE ATT&CK TTP -> articles."""
    ttp_map: dict[str, list[dict]] = {}
    for a in articles:
        for t in as_list(a["fm"].get("attack_ttps", a["fm"].get("attack_ttp"))):
            ttp_map.setdefault(t, []).append(a)

    lines = header("ATT&CK TTP Index", "Which articles cover a given MITRE ATT&CK technique.")
    lines += ["| TTP ID | Articles |", "|---|---|"]
    for ttp, arts in sorted(ttp_map.items()):
        links = ", ".join(f"[[{art['wiki_link']}|{art['title']}]]" for art in arts)
        lines.append(f"| {ttp} | {links} |")
    if not ttp_map:
        lines.append("| - | *(No ATT&CK TTPs indexed yet)* |")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Health checks
# ---------------------------------------------------------------------------

def validate_frontmatter(articles: list[dict]) -> list[str]:
    """One error per article with missing required YAML fields (navigation pages are skipped)."""
    errors = []
    for a in articles:
        if not is_article(a):
            continue
        if not a["fm"]:
            errors.append(f"{a['rel_path']} -> missing YAML frontmatter")
            continue
        missing = [f for f in REQUIRED_FIELDS if not a["fm"].get(f)]
        if not article_sources(a["fm"]):
            missing.append("sources")
        if missing:
            errors.append(f"{a['rel_path']} -> missing fields: {', '.join(missing)}")
        art_type = str(a["fm"].get("type") or "").strip()
        if art_type and art_type not in VALID_TYPES:
            errors.append(f"{a['rel_path']} -> unknown type '{art_type}' (allowed: {', '.join(VALID_TYPES)})")
    return errors


def validate_links(wiki_dir: Path, articles: list[dict]) -> tuple[list[str], list[str], list[str]]:
    """Returns (dead_links, orphans, no_outlinks)."""
    known_nodes = set()
    for p in wiki_dir.rglob("*.md"):
        rel = p.relative_to(wiki_dir).as_posix()[:-3]
        known_nodes.add(f"wiki/{rel}".lower())

    dead_links, no_outlinks = [], []
    referenced = set()
    for a in articles:
        targets = extract_links(a["content"], a["path"], wiki_dir)
        if not targets and is_article(a):
            no_outlinks.append(a["rel_path"])
        for t in targets:
            referenced.add(t)
            if t not in known_nodes:
                dead_links.append(f"{a['rel_path']} -> [[{t}]]")

    # The generated master index links everything, so it is not counted (it is not in `articles`).
    orphans = [a["rel_path"] for a in articles if is_article(a) and a["wiki_link"].lower() not in referenced]
    return dead_links, orphans, no_outlinks


def unprocessed_raw_files(project_root: Path) -> list[str]:
    feeds = project_root / "knowledge_base" / "raw" / "feeds"
    if not feeds.exists():
        return []
    return sorted(
        str(p.relative_to(project_root))
        for p in feeds.glob("*.md")
        if not p.stem.endswith("_processed")
    )


def report(label: str, items: list[str], limit: int = 10) -> None:
    print(label)
    for item in items[:limit]:
        print(f"    - {item}")
    if len(items) > limit:
        print(f"    … and {len(items) - limit} more")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def load_articles(wiki_dir: Path, project_root: Path) -> list[dict]:
    articles = []
    for f in get_wiki_files(wiki_dir):
        text = f.read_text(encoding="utf-8")
        fm, body = extract_frontmatter(text)
        rel_posix = f.relative_to(wiki_dir).as_posix()

        title = next(
            (line.strip()[2:].strip() for line in body.splitlines() if line.strip().startswith("# ")),
            f.stem.replace("-", " ").title(),
        )
        articles.append({
            "path": f,
            "rel_path": str(f.relative_to(project_root)),
            "wiki_link": f"wiki/{rel_posix[:-3]}",
            "title": title,
            "topic": rel_posix.split("/")[0] if "/" in rel_posix else "general",
            "fm": fm,
            "content": text,
        })
    return articles


def main():
    parser = argparse.ArgumentParser(description="Deterministic KB Index Builder and Validator")
    parser.add_argument("--check", action="store_true", help="Report health only, do not write files")
    parser.add_argument("--open", action="store_true", help="Open knowledge graph visualizer in browser")
    args = parser.parse_args()

    project_root = Path(__file__).resolve().parent.parent.parent
    wiki_dir = project_root / "knowledge_base" / "wiki"
    if not wiki_dir.exists():
        print(f"Error: Wiki directory not found at {wiki_dir}")
        sys.exit(1)

    articles = load_articles(wiki_dir, project_root)
    dead_links, orphans, no_outlinks = validate_links(wiki_dir, articles)
    fm_errors = validate_frontmatter(articles)
    raw_pending = unprocessed_raw_files(project_root)

    print(f"[*] Scanned {sum(is_article(a) for a in articles)} wiki articles.")
    if dead_links:
        report(f"[!] Error: {len(dead_links)} dead links:", dead_links)
    else:
        print("[✓] Zero dead links.")
    if fm_errors:
        report(f"[!] Error: {len(fm_errors)} frontmatter problems "
               f"(required: {', '.join(REQUIRED_FIELDS)}, sources):", fm_errors)
    else:
        print("[✓] All articles have required frontmatter.")
    if orphans:
        report(f"[*] Note: {len(orphans)} orphan articles (no other article links to them):", orphans, 5)
    if no_outlinks:
        report(f"[*] Note: {len(no_outlinks)} articles with no outgoing links:", no_outlinks, 5)
    if raw_pending:
        report(f"[*] Note: {len(raw_pending)} raw files not compiled yet:", raw_pending, 5)

    exit_code = 1 if (dead_links or fm_errors) else 0

    if args.check:
        print("[*] Check mode complete." + (" Fix the errors above." if exit_code else ""))
        sys.exit(exit_code)

    # Generate indexes (only files whose content changed are rewritten)
    outputs = {
        MASTER_INDEX: build_master_index(articles),
        TOOLS_INDEX: build_tools_index(articles),
        TTP_INDEX: build_ttp_index(articles),
    }
    changed = [name for name, content in outputs.items() if write_if_changed(wiki_dir / name, content)]
    for legacy in LEGACY_INDEXES:
        path = wiki_dir / legacy
        if path.exists() and GENERATED_MARKER in path.read_text(encoding="utf-8"):
            path.unlink()
            changed.append(f"{legacy} (removed)")
    print(f"[✓] Indexes updated: {', '.join(changed)}" if changed else "[✓] Indexes already up to date.")

    # Sync graph
    graph_script = project_root / ".kb" / "scripts" / "graph_generator.py"
    if graph_script.exists():
        import subprocess
        cmd = [sys.executable, str(graph_script)]
        if args.open:
            cmd.append("--open")
        sys.stdout.flush()
        subprocess.run(cmd)

    if exit_code:
        print("[!] Indexes were written, but the KB has errors (see above). Fix them and re-run.")
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
